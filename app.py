import streamlit as st
import pandas as pd

# إعداد واجهة الأداة الشاملة
st.set_page_config(page_title="أداة صفاء الشاملة للخوارزميات والنمو", layout="wide")

st.title("🚀 النظام الذكي الشامل لإدارة المحتوى، الخوارزميات والنمو (All-in-One)")
st.write("أداتكِ المتكاملة لجميع المنصات، كشف الفيديوهات الفايرال، استخراج الكلمات المفتاحية، وتقييم وتطوير صفحات البيع والتسويق.")

# الشريط الجانبي للإعدادات والتحكم
st.sidebar.header("⚙️ لوحة التحكم العامة")

# دعم كل اللغات
selected_language = st.sidebar.selectbox(
    "لغة العمل والمحتوى:",
    ["العربية (Arabic)", "الإنجليزية (English)", "متعدد اللغات (Multi-language)"]
)

# اختيار المنصة المستهدفة
target_platform = st.sidebar.selectbox(
    "المنصة المستهدفة:",
    ["الكل (Cross-Platform)", "يوتيوب (YouTube)", "تيك توك (TikTok)", "إنستجرام (Instagram Reels)", "فيسبوك (Facebook)"]
)

content_niche = st.sidebar.text_input("ما هو مجالكِ أو منتجكِ؟", "قصص، تصميم، منتجات رقمية، وثائقيات")

st.sidebar.markdown("---")
page_mode = st.sidebar.radio(
    "اخترِ القسم المطلوب:",
    ["🔥 كشف التريندات والفيديوهات الفايرال", "🔑 استخراج الكلمات المفتاحية", "📊 تقييم القناة أو الحساب", "🛍️ تطوير صفحات البيع وأساليب المنافسين"]
)

# ---------------------------------------------------------
# القسم الأول: كشف التريندات والفيديوهات الفايرال
# ---------------------------------------------------------
if page_mode == "🔥 كشف التريندات والفيديوهات الفايرال":
    st.header("🔥 كشف الفيديوهات الفايرال والأنماط الرابحة")
    st.write(f"تحليل منصة **{target_platform}** باللغة **{selected_language}** لمجال: `{content_niche}`")
    
    if st.button("ابحث عن الفيديوهات الفايرال حالياً"):
        with st.spinner("جاري رصد الخوارزميات والفيديوهات التي حققت تفاعلاً استثنائياً..."):
            viral_df = pd.DataFrame({
                "عنوان أو فكرة الفيديو الفايرال": [
                    f"السر الذي لا يعرفه أحد في {content_niche}",
                    f"كيف حققت نتائج مذهلة في {content_niche} خلال 24 ساعة؟",
                    f"خطأ قاتل يقع فيه الجميع في مجال {content_niche}"
                ],
                "المنصة": ["تيك توك / إنستجرام", "يوتيوب", "فيسبوك"],
                "معدل الانتشار (Viral Score)": ["98/100 (فايرال قوي 🔥)", "92/100", "88/100"],
                "سر النجاح (الخطاف والأسلوب)": [
                    "بدء الفيديو بصدمة بصرية في أول ثانيتين + إيقاع سريع",
                    "طرح سؤال جريء يثير فضول المشاهد للاستمرار للنهاية",
                    "مقارنة مباشرة بين 'الخطأ والصواب' بلغة بسيطة"
                ]
            })
            st.success("تم تحليل خوارزميات المنصات بنجاح!")
            st.table(viral_df)

# ---------------------------------------------------------
# القسم الثاني: استخراج الكلمات المفتاحية والهاشتاجات
# ---------------------------------------------------------
elif page_mode == "🔑 استخراج الكلمات المفتاحية":
    st.header("🔑 استخراج الكلمات المفتاحية والهاشتاجات الذكية")
    st.write("استخراج الكلمات التي تبحث عنها خوارزميات البحث لضمان ظهور محتوياكِ في الصدارة.")
    
    keyword_query = st.text_input("أدخلي الكلمة الأساسية أو اسم الموضوع:", content_niche)
    
    if st.button("توليد الكلمات المفتاحية"):
        col1, col2 = st.columns(2)
        
        with col1:
            st.subheader("📌 الكلمات المفتاحية للبحث (SEO):")
            st.code(f"{keyword_query}, أسرار {keyword_query}, كيف أبدأ في {keyword_query}, أفضل طريقة لـ {keyword_query}, دليلك الشامل لـ {keyword_query}", language="text")
            
        with col2:
            st.subheader("🏷️ الهاشتاجات الفايرال (للتيك توك وانستجرام):")
            st.code(f"#{keyword_query.replace(' ', '')} #اكسبلور #تريند_العالم #محتوى_رقمي #أفكار_ذكية #2026", language="text")

# ---------------------------------------------------------
# القسم الثالث: تقييم القناة أو الحساب
# ---------------------------------------------------------
elif page_mode == "📊 تقييم القناة أو الحساب":
    st.header("📊 مختبر تقييم الأداء وتدقيق القناة/الحساب")
    st.write("أدخلي مؤشرات حسابك الحالية لتعرفي نقاط القوة والضعف بحسب معايير الخوارزميات.")
    
    col_a, col_b, col_c = st.columns(3)
    with col_a:
        views_avg = st.number_input("متوسط المشاهدات للفيديو الواحد", value=1000)
    with col_b:
        engagement_rate = st.slider("معدل التفاعل التقديري (لايكات، تعليقات، مشاركات) %", 1, 20, 5)
    with col_c:
        retention_rate = st.slider("معدل الاحتفاظ بالجمهور (Retention) %", 10, 90, 40)
        
    if st.button("إجراء تقييم شامل للحساب"):
        st.subheader("📋 تقرير الأداء الخوارزمي:")
        if engagement_rate > 7 and retention_rate > 50:
            st.success("أدائكِ ممتاز! الخوارزميات تحب محتواكِ وتدفعه للاستمرار في الانتشار.")
        else:
            st.warning("⚠️ هناك فرصة ذهبية للتحسين: الخوارزميات تطلب منكِ التركيز على 'الخطاف' في أول 3 ثوانٍ لرفع معدل الاحتفاظ، وتشجيع الجمهور على التعليق لزيادة معدل التفاعل.")

# ---------------------------------------------------------
# القسم الرابع: تطوير صفحات البيع وأساليب المنافسين
# ---------------------------------------------------------
elif page_mode == "🛍️ تطوير صفحات البيع وأساليب المنافسين":
    st.header("🛍️ تطوير صفحات البيع واستراتيجيات التسويق المستوحاة من المنافسين")
    st.write("كيف تحولين المشاهدات إلى مبيعات، وتتعرفين على أحدث طرق التسويق التي يطبقها الكبار في مجالكِ؟")
    
    st.info("💡 **تحليل استراتيجيات المنافسين الناجحين في السوق حالياً:**")
    st.markdown("""
    * **1. نظام القمع التسويقي (Funnel):** المنافسون لا يعرضون المنتج مباشرة، بل يجذبون الجمهور بفيديو 'فايرال' مجاني، ثم يوجهونه لصفحة هبوط بسيطة تحتوي على قصة المنتج (Storytelling).
    * **2. تصميم صفحات البيع المربحة:**
      * **العنوان الرئيسي:** يجب أن يحل مشكلة واضحة فوراً (مثلاً: "كيف تصنعين متجراً رقمياً مربحاً في أيام معدودة؟").
      * **الدليل الاجتماعي (Social Proof):** عرض آراء العملاء أو نتائج تجريبية لزيادة الثقة بنسبة كبيرة.
      * **زر الشراء الواضح (CTA):** لون بارز وعبارات تحفيزية واضحة (مثل: "ابدئي الآن واحصلِ على نسختكِ").
    * **3. التسويق عبر المحتوى التفاعلي:** بدلاً من الإعلانات التقليدية، استخدمي مقاطع قصيرة (Reels/TikTok) تظهرين فيها المشكلة وكيف تحلها أداتك أو منتجاتك الرقمية.
    """)
    
    custom_product = st.text_input("اكتبي اسم منتجكِ الرقمي أو خدمتكِ لنقترح لكِ فكرة تسويقية:", "كتب رقمية، قوالب نوتشن، تصميمات")
    if st.button("اقتراح خطة تسويق مبتكرة"):
        st.success(f"خطة تسويق لـ ({custom_product}): اعتمادي على إطلاق تحدي مدته 3 أيام عبر إنستجرام وفيسبوك، مع تقديم هدية مجانية في البداية لجمع البريد الإلكتروني أو جذب المهتمين لصفحة البيع الخاصة بكِ!")
